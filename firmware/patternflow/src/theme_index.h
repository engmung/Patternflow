// Served at /pf-console.js by core_http.h. Every page loads it as one
// parser-blocking <script src> in <head>; console_pages.py stamps that tag
// as /pf-console.js?h=<CRC32 of this literal> (immutable under its own h)
// and follows it with console/_pf_fallback.js, a minimal PF for when this
// file failed to load. So any edit here changes every page header: run
