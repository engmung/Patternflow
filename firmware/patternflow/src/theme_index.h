// At parse time (no network): the theme stamp from localStorage 'pf-theme'
// before first paint; head CSS (light palette = the union of every page's
// variable families, color-scheme, a placeholder band of exactly
// --pf-chrome-h so nothing moves when the header mounts, 16px inputs on
// touch screens because iOS zooms into smaller ones, .pf-busy); the fetch
// wrapper, which gives every same-origin GET/HEAD without its own signal an
// AbortController so a tab switch can free the panel's single connection
// instead of queueing behind it; and window.PF.
//
// At DOMContentLoaded it mounts <pf-chrome id="pfChrome"> as body's first
// child, everything inside an open shadow root so no page CSS reaches it and
// its CSS reaches no page (pages must not reach into it either). Heights are
// fixed: phone = 40px brand row + 40px nav row + 1px rule = 81px, >=720px =
// one 40px row + rule = 41px, the values of --pf-chrome-h.
//
// The nav is the core's pages only; features contribute theirs through
// /api/status featureNav, spliced in after Patterns. (This file once named
// three optional features by path, so a build without them drew dead links.)
// Every href carries ?v=<build>, which the device serves immutable, so a tab
// switch after the first visit costs no request. The last nav drawn is kept
// in localStorage 'pf-nav' and reused when its build matches the page's.
// A variant (not core) gets a badge linking to its shelf entry so someone
// who did not flash the panel can tell what it runs; the version text then
// says "core v", since unlabelled it would read as the variant's.
// Links to patternflow.work get ?device=<this panel> at click time so the
// site can reach the panel without patternflow.local resolving.
//
// Background lane: one PF request in flight per document, FIFO, because the
// panel serves one connection at a time and parallel polls only queue there.
// Lane timeouts are clamp(4 x EWMA RTT, 12 s, 30 s), applied to the reply and
// again to its body; two failures in a row, timeouts included, make the
// state offline - one slow reply does not. Version check: a page whose build differs from the
// device's replaces itself once per path per build (sessionStorage
// 'pf-heal:<path>:<build>') unless someone is mid-edit; else the chip offers
// it. Prefetch warms the nav pages' versioned URLs only on a quiet, fast,
// non-hotspot link (lease: localStorage 'pf-prefetch'; once per session and
// build: sessionStorage 'pf-pf:<build>'). Holds are announced to other tabs
// on BroadcastChannel 'pf' (fallback: the storage event on 'pf-hold').
//
// The page API (window.PF):
//   PF.v                   this page's ?v= build, or null (adopted from the first status on a bare URL)
//   PF.state               'connecting' | 'live' | 'offline' | 'restarting'; html gets pf-<state> unless live
//   PF.dirty               set true while the page holds unsaved edits: blocks the automatic version reload
//   PF.inflight()          number of the page's own GETs in flight
//   PF.get(url, opts)      foreground GET -> Promise of JSON (opts.text: text; opts.timeout: ms); rejects with .status/.timeout;
//                          a reply from another origin leaves PF.state alone
//   PF.poll(src, ms, cb, opts)  chained poll on the lane -> {stop(), now(), set(ms)}; src = URL or fn() -> Promise; cb(data, null) | cb(null, err); opts.first === false waits ms
//   PF.status(cb)          cb(status) on every fresh /api/status (at once if one is known); never stale
//   PF.watchStatus(ms)     keep status fresh at the smallest interval any caller asked for
//   PF.hold(promise, opts) pause this tab's lane and slow other tabs until it settles (10 min max); opts.guard confirms leaving
//   PF.say(text, kind, el) kind 'ok' | 'err' | 'info'; into el (class pf-<kind>, 'ok' clears after 4 s) or a toast
