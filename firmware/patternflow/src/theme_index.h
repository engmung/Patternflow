// nav cannot fit (many features, or the chip showing) wraps under it with
// brand, chip and toggle staying on the first line. The chip and the toggle
// are 40px tap targets (the chip draws its 30px pill inside a transparent
// border).
//
// The nav is the core's pages only; features contribute theirs through
// /api/status featureNav, spliced in after Patterns. Order: Console,
// Patterns, the features, then the setup group (Wi-Fi, Knobs, Update,
